अन्नकूट का भोग लगाने से भक्त के घर में अन्न की कभी कमी नहीं होती।”

गोवर्धन पूजा और गाय की महिमा:

ब्रजवासियों ने पूछा —

“गिरिराज! गायों का क्या महात्म्य है? उन्हें इस पूजा में विशेष स्थान क्यों दिया जाता है?”

गिरिराज ने कहा —

“गाय माता के समान है। वह दूध देती है, जिससे बच्चे पलते हैं। वह गोबर देती है, जिससे खेत उपजाऊ होते हैं। वह गोमूत्र देती है, जो औषधि है। गाय के बिना जीवन सम्भव नहीं। जब भगवान श्रीकृष्ण ने मुझे धारण किया, तब ब्रजवासियों की गायें मेरी छाया में सुरक्षित रहीं। इसलिए गोवर्धन पूजा में गायों की पूजा अनिवार्य है।

जो गायों की सेवा करता है, वह मेरी और श्रीकृष्ण की सेवा करता है। गाय की सेवा से सभी पाप नष्ट होते हैं और सभी मनोकामनाएँ पूर्ण होती हैं।”

इन्द्रदेव का प्रश्न:

इन्द्रदेव ने पूछा —

“गिरिराज! मैंने अपने अभिमान में आकर ब्रजवासियों पर वर्षा की। अब मैं जानना चाहता हूँ — मेरा क्या कर्तव्य है?”

गिरिराज ने कहा —

