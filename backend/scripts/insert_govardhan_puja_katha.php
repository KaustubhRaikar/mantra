श्रीकृष्ण ने मुस्कुराकर कहा —

“इन्द्रदेव! तुम्हारा प्रश्न उत्तम है। मैं तुम्हें गोवर्धन पूजा का सम्पूर्ण महात्म्य बताऊँगा।”

