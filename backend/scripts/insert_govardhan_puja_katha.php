मुझे अन्नकूट पर्वत भी कहा जाता है, क्योंकि मेरे ऊपर अनेक वनस्पतियाँ, औषधियाँ और अन्न उगते हैं। मैं ब्रजभूमि की रक्षा करता हूँ, वर्षा को धारण करता हूँ, नदियों को जन्म देता हूँ। मैं ही हूँ जो ब्रजवासियों को चारा, जल और अन्न प्रदान करता हूँ।”

इन्द्रदेव ने पूछा —

“गिरिराज! यदि आप इतने महान हैं, तो आप अपने महात्म्य से पृथ्वी पर सब कुछ दे सकते हैं? फिर मेरी आवश्यकता क्या है?”

गिरिराज ने मुस्कुराकर कहा —

“इन्द्रदेव! तुम भी महान हो। तुम वर्षा करते हो, जिससे मेरे ऊपर वनस्पतियाँ उगती हैं। हम दोनों एक-दूसरे के पूरक हैं। परन्तु तुमने अभिमान किया कि तुम्हारे बिना कुछ नहीं हो सकता। यही तुम्हारी भूल थी। सत्य यह है कि सब कुछ ईश्वर की कृपा से होता है — न तुमसे, न मुझसे। हम तो केवल निमित्त हैं।”

इन्द्रदेव ने यह सुना और उनका अभिमान पूर्णतः चूर हो गया।

गोवर्धन पूजा का महात्म्य:

श्रीकृष्ण ने कहा —

“गिरिराज! अब तुम ब्रजवासियों को गोवर्धन पूजा की विधि और महात्म्य बताओ।”

गिरिराज गोवर्धन ने कहा —

