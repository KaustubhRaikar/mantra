अन्नकूट में छप्पन प्रकार के भोग होते हैं। छप्पन का अर्थ है — पूर्णता। यह प्रतीक है कि भक्त अपना सर्वस्व भगवान को अर्पित करता है।

अन्नकूट बनाने की विधि यह है —

- सभी प्रकार के अन्न, दाल, सब्जियाँ, फल और मिष्ठान एक साथ एकत्र करो।
- उन्हें एक बड़े बर्तन या थाली में सजाओ — पर्वत के आकार में।
- इसे मेरे सम्मुख रखो और मुझे अर्पित करो।
- फिर प्रसाद के रूप में सभी को बाँटो।

अन्नकूट का भोग लगाने से भक्त के घर में अन्न की कभी कमी नहीं होती। जो भक्त अन्नकूट का भोग लगाता है, उसे अक्षय अन्न का आशीर्वाद मिलता है।”

गाय की महिमा:

नारदजी ने पूछा —

“गिरिराज! गायों का क्या महात्म्य है? उन्हें इस पूजा में विशेष स्थान क्यों दिया जाता है?”

गिरिराज ने कहा —

“देवर्षि! गाय माता के समान है। वह दूध देती है, जिससे बच्चे पलते हैं। वह गोबर देती है, जिससे खेत उपजाऊ होते हैं। वह गोमूत्र देती है, जो औषधि है। गाय के बिना जीवन सम्भव नहीं।

जब श्रीकृष्ण ने मुझे धारण किया, तब ब्रजवासियों की गायें मेरी छाया में सुरक्षित रहीं। इसलिए गोवर्धन पूजा में गायों की पूजा अनिवार्य है।

जो गायों की सेवा करता है, वह मेरी और श्रीकृष्ण की सेवा करता है। गाय की सेवा से सभी पाप नष्ट होते हैं और सभी मनोकामनाएँ पूर्ण होती हैं।”

गोवर्धन पूजा का फल:

नारदजी ने पूछा —

“गिरिराज! इस पूजा से कौन-कौन से फल प्राप्त होते हैं?”

गिरिराज ने कहा —

“देवर्षि! जो भक्त श्रद्धा और भक्ति से यह पूजा करता है —

- उसके घर में अन्न-धन की कमी नहीं होती।
- उसकी गायें सदा स्वस्थ रहती हैं और अधिक दूध देती हैं।
- उसके खेत हरे-भरे रहते हैं।
- उसके बच्चे सुरक्षित रहते हैं।
- उसके जीवन से भय दूर होता है।
- उसे इन्द्रदेव जैसे देवताओं का प्रकोप नहीं सताता।
- उसका जीवन स्थिर और शान्त रहता है।
- जो स्त्री यह पूजा करती है, उसका सौभाग्य अखण्ड रहता है।
- जो पुरुष यह पूजा करता है, उसके कार्य सफल होते हैं।
- जो कन्या यह पूजा करती है, उसे योग्य वर मिलता है।
- जो व्यापारी यह पूजा करता है, उसके व्यापार में वृद्धि होती है।
- जो किसान यह पूजा करता है, उसके खेतों में सदा अन्न उगता है।
- जो स्त्री सन्तान की इच्छा रखती है, उसे सन्तान-सुख मिलता है।
- जो भक्त यह पूजा करता है, उसे श्रीकृष्ण की विशेष कृपा प्राप्त होती है।

परन्तु देवर्षि, सबसे बड़ा फल यह है कि जो मेरी पूजा करता है, वह श्रीकृष्ण की कृपा प्राप्त करता है। क्योंकि मैं श्रीकृष्ण का प्रिय हूँ, और श्रीकृष्ण मेरे प्रिय हैं। जो मेरी शरण में आता है, वह स्वयं श्रीकृष्ण की शरण में आ जाता है।”

इन्द्रदेव का अभिमान-भंग और शिक्षा:

नारदजी ने पूछा —

“गिरिराज! इन्द्रदेव ने अपने अभिमान में आकर ब्रजवासियों पर वर्षा की। इससे क्या शिक्षा मिलती है?”

गिरिराज ने कहा —

“देवर्षि! इससे यह शिक्षा मिलती है कि अभिमान सबसे बड़ा शत्रु है। इन्द्रदेव वर्षा के देवता थे, परन्तु उन्होंने अभिमान किया कि उनके बिना ब्रजवासी जीवित नहीं रह सकते। उनका अभिमान श्रीकृष्ण ने तोड़ा।

इससे यह भी शिक्षा मिलती है कि भक्ति में अहंकार नहीं होना चाहिए। जो भक्त अहंकार करता है, उसका व्रत निष्फल हो जाता है। जो विनम्र है, उसे भगवान की कृपा प्राप्त होती है।

तीसरी शिक्षा यह है कि प्रकृति और मनुष्य का सहअस्तित्व है। ब्रजवासियों ने गोवर्धन पर्वत, गायों और ब्रजभूमि की पूजा की — ये सभी प्रकृति के अंग हैं। जो प्रकृति की रक्षा करता है, प्रकृति उसकी रक्षा करती है।”

गोवर्धन पूजा और वैज्ञानिक दृष्टिकोण:

नारदजी ने पूछा —

“गिरिराज! क्या गोवर्धन पूजा का कोई वैज्ञानिक महात्म्य भी है?”

गिरिराज ने मुस्कुराकर कहा —

“देवर्षि! सनातन धर्म में हर परम्परा के पीछे कोई न कोई वैज्ञानिक कारण होता है। गोवर्धन पूजा का भी वैज्ञानिक महात्म्य है —

- कार्तिक मास में मौसम परिवर्तन: कार्तिक मास में शरद ऋतु का अन्त और शिशिर ऋतु का आरम्भ होता है। इस समय वर्षा कम हो जाती है। गोवर्धन पूजा से पहले वर्षा ऋतु में खेतों में अन्न उगता है और गोवर्धन पूजा के समय फसल कटाई का समय आता है। यह पूजा कृषि-चक्र से जुड़ी है।
- गोबर से बनी आकृति: गोबर में एंटीबैक्टीरियल गुण होते हैं। गोवर्धन की आकृति बनाने से घर का वातावरण शुद्ध होता है।
- अन्नकूट: छप्पन प्रकार के भोजन से शरीर को सभी प्रकार के पोषक तत्व मिलते हैं। यह सन्तुलित आहार का प्रतीक है।
- गायों की पूजा: गाय का दूध, गोबर और गोमूत्र — तीनों औषधीय गुणों से भरपूर हैं। गाय की सेवा से स्वास्थ्य लाभ होता है।
- परिक्रमा: गोवर्धन की परिक्रमा से शारीरिक व्यायाम होता है और मानसिक शान्ति मिलती है।
- सामूहिक भक्ति: सभी मिलकर पूजा करते हैं — इससे सामाजिक एकता बढ़ती है।

इस प्रकार गोवर्धन पूजा आध्यात्मिक और वैज्ञानिक — दोनों दृष्टियों से महत्वपूर्ण है।”

फलश्रुति:

गिरिराज गोवर्धन ने कहा —

“देवर्षि! जो व्यक्ति इस गोवर्धन पूजा व्रत कथा को श्रद्धापूर्वक सुनता है, वह इस पूजा का सम्पूर्ण फल प्राप्त करता है। जो स्त्री इस कथा को सुनकर पूजा करती है, उसका सौभाग्य अखण्ड रहता है। जो कन्या इस कथा को सुनती है, उसे योग्य वर मिलता है। जो पुरुष इस कथा को सुनता है, उसके कार्य सफल होते हैं। जो किसान इस कथा को सुनता है, उसके खेत हरे-भरे रहते हैं। जो व्यापारी इस कथा को सुनता है, उसके व्यापार में वृद्धि होती है।

जो इस कथा को पढ़ता या सुनाता है, उसे श्रीकृष्ण और मेरी विशेष कृपा प्राप्त होती है। यह कथा जिस घर में सुनी जाती है, वहाँ सुख, समृद्धि और शान्ति बनी रहती है। जो इस कथा को प्रत्येक गोवर्धन पूजा में सुनता है, उसकी सभी मनोकामनाएँ पूर्ण होती हैं।

जो भक्त यह पूजा करता है, उसे अहिंसा का पालन अवश्य करना चाहिए। यदि वह गायों को हानि पहुँचाता है या प्रकृति को नष्ट करता है, तो उसकी पूजा निष्फल हो जाती है। इसलिए सभी को चाहिए कि वे गायों की रक्षा करें और प्रकृति का संरक्षण करें।”

समापन:

इसके बाद गिरिराज गोवर्धन ने श्रीकृष्ण को प्रणाम किया और कहा —

“प्रभु! आपने मुझे अपने हाथ पर धारण कर मुझे धन्य किया। मैं सदा आपका ऋणी रहूँगा। आज से जो भी भक्त मेरी पूजा करेगा, मैं उसकी रक्षा करूँगा।”

श्रीकृष्ण ने मुस्कुराकर कहा —

“गिरिराज! तुम्हारी कीर्ति सदा तीनों लोकों में गाई जाएगी। जो तुम्हारी पूजा करेगा, वह मेरी पूजा करेगा। जो तुम्हारी शरण में आएगा, वह मेरी शरण में आएगा।”

यह कहकर गिरिराज गोवर्धन अन्तर्धान हो गए।

नारदजी ने श्रीकृष्ण को प्रणाम किया और कहा —

“कन्हैया! आज मैंने गोवर्धन पूजा का सम्पूर्ण महात्म्य सुना। अब मैं इसे सारे संसार में प्रचारित करूँगा।”

श्रीकृष्ण ने कहा —

“नारदजी! जो इस कथा को सुनकर गोवर्धन पूजा करेगा, उसे मेरी विशेष कृपा प्राप्त होगी।”

उस दिन से नारदजी ने गोवर्धन पूजा का प्रचार सारे संसार में किया। ब्रजवासियों ने प्रत्येक वर्ष गोवर्धन पूजा करना जारी रखा। धीरे-धीरे यह पूजा सारे भारत में प्रसिद्ध हो गई।

आज भी भारत के अनेक भागों में — विशेष रूप से मथुरा, वृन्दावन, गोकुल, नाथद्वारा और गुजरात में — गोवर्धन पूजा अत्यन्त श्रद्धा और उल्लास से मनाई जाती है। लोग गोबर से गोवर्धन पर्वत की आकृति बनाते हैं, गायों को सजाते हैं, अन्नकूट का भोग लगाते हैं और गिरिराज गोवर्धन की परिक्रमा करते हैं।

गोवर्धन पूजा का यह व्रत आज भी भक्तों को यह शिक्षा देता है कि अभिमान का नाश होता है, विनम्रता का उद्धार होता है। जो प्रकृति और गोवंश की रक्षा करता है, उसे श्रीकृष्ण की कृपा प्राप्त होती है।

इति श्री गोवर्धन पूजा व्रत कथा सम्पूर्णम्।

ॐ गोवर्धनाय नमः।
गिरिराज गोवर्धन धरो, शरण तिहारी आयो।
कृष्ण कृपा से दुख हरो, सुख सम्पत्ति पायो॥
