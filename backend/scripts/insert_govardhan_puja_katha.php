1. पूजा का दिन: कार्तिक मास की शुक्ल प्रतिपदा — दीपावली के अगले दिन — गोवर्धन पूजा का दिन है। इस दिन जो भक्त मेरी पूजा करता है, उसके जीवन से सारे कष्ट दूर हो जाते हैं।

2. मेरी प्रतिमा बनाना: गोबर या मिट्टी से मेरी आकृति बनाओ। यह आकृति मेरे पर्वत स्वरूप का प्रतीक है। इसे सजाओ और मेरा पूजन करो।

3. गायों की पूजा: मेरी पूजा के साथ गायों की पूजा अवश्य करो। गायें माता के समान हैं — वे दूध देती हैं, गोबर देती हैं जिससे अन्न उगता है। गायों की सेवा से मेरी प्रसन्नता होती है।

4. अन्नकूट का भोग: अन्नकूट का अर्थ है — अन्न का पर्वत। छप्पन प्रकार के भोग मुझे अर्पित करो। यह प्रतीक है कि जैसे मेरे ऊपर अनेक वनस्पतियाँ उगती हैं, वैसे ही भक्त के घर में अन्न की कमी न हो।

5. परिक्रमा: मेरी सात परिक्रमा करो। यह सात वचनों का प्रतीक है — जो तुमने मुझे दिए हैं। परिक्रमा में यह मंत्र बोलो —

‘ॐ गोवर्धनाय नमः। गिरिराज नमस्ते। मम रक्षां कुरु कुरु।’

6. दीपदान: मेरे नीचे दीपक जलाओ। यह प्रकाश का प्रतीक है — जो अंधकार को दूर करता है। दीपक जलाने से तुम्हारे जीवन से अज्ञान का अंधकार दूर होगा।

7. गोवर्धन की मिट्टी: मेरी मिट्टी को पवित्र मानो। उसे अपने माथे पर लगाओ। यह मेरी कृपा का प्रतीक है।”

ब्रजवासियों ने पूछा —

“गिरिराज! हमें यह पूजा क्यों करनी चाहिए? इसका फल क्या है?”

गिरिराज ने कहा —

“जो भक्त मेरी पूजा करता है —

- उसके घर में अन्न-धन की कमी नहीं होती।
- उसकी गायें सदा स्वस्थ रहती हैं और अधिक दूध देती हैं।
- उसके खेत हरे-भरे रहते हैं।
- उसके बच्चे सुरक्षित रहते हैं।
- उसके जीवन से भय दूर होता है।
- उसे इन्द्रदेव जैसे देवताओं का प्रकोप नहीं सताता।
- उसका जीवन स्थिर और शान्त रहता है।
- जो स्त्री यह पूजा करती है, उसका सौभाग्य अखण्ड रहता है।
- जो पुरुष यह पूजा करता है, उसके कार्य सफल होते हैं।
- जो कन्या यह पूजा करती है, उसे योग्य वर मिलता है।
- जो व्यापारी यह पूजा करता है, उसके व्यापार में वृद्धि होती है।

परन्तु सबसे बड़ा फल यह है कि जो मेरी पूजा करता है, वह श्रीकृष्ण की कृपा प्राप्त करता है। क्योंकि मैं श्रीकृष्ण का प्रिय हूँ, और श्रीकृष्ण मेरे प्रिय हैं। जो मेरी शरण में आता है, वह स्वयं श्रीकृष्ण की शरण में आ जाता है।”

अन्नकूट का महात्म्य:

ब्रजवासियों ने पूछा —

“गिरिराज! अन्नकूट का क्या महात्म्य है? इसे कैसे बनाया जाता है?”

गिरिराज ने कहा —

“अन्नकूट का अर्थ है — अन्न का पर्वत। जब भगवान श्रीकृष्ण ने मुझे अपने हाथ पर धारण किया, तब ब्रजवासियों ने सात दिन तक मेरी छाया में निवास किया। उन सात दिनों में उन्होंने जो भोजन बनाया, वह सब मेरे नीचे एकत्र हो गया। उस भोजन का ढेर पर्वत के समान हो गया — इसलिए इसे अन्नकूट कहा गया।

अन्नकूट में छप्पन प्रकार के भोग होते हैं — पूरी, कचौड़ी, हलवा, खीर, सब्जियाँ, दाल, चावल, पकौड़े, मिठाइयाँ आदि। यह प्रतीक है कि भक्त अपना सर्वस्व भगवान को अर्पित करता है।

