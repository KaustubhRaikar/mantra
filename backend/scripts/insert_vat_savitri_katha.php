“माँ! आपने मुझे दर्शन दिए। मैं धन्य हूँ।”

माँ सावित्री ने मुस्कुराकर कहा —

“पुत्रि! उठो। तूने अपने तप, पतिव्रता और धर्म के बल से यमराज को भी पराजित किया। तू मेरी ही अंश है। तेरी भक्ति और दृढ़ संकल्प से मैं प्रसन्न हूँ। अब तू जो पूछना चाहती है, वह सुन।”

माँ सावित्री का प्रादुर्भाव:

माँ सावित्री बोलीं —

“पुत्रि! सुनो, मैं तुम्हें इस व्रत का सम्पूर्ण रहस्य बताती हूँ। जब ब्रह्माजी ने सृष्टि की रचना की, तब उन्होंने सभी जीवों को जीवन प्रदान किया। परन्तु जीवों को सत्य, धर्म और पतिव्रता का ज्ञान नहीं था। तब ब्रह्माजी ने अपनी दिव्य शक्ति से मुझे प्रकट किया।

मैं सावित्री हूँ — सत्य की देवी, धर्म की रक्षक और पतिव्रता की अधिष्ठात्री। मैं सूर्यदेव की पुत्री हूँ और ब्रह्माजी की शक्ति हूँ। जो स्त्री पतिव्रता का पालन करती है, मैं उसकी रक्षा करती हूँ। जो स्त्री अपने पति के लिए तप करती है, मैं उसकी शक्ति बनती हूँ।

मेरा वट वृक्ष से अत्यन्त गहरा सम्बन्ध है। वट वृक्ष अक्षय है — यह कभी नष्ट नहीं होता। इसकी जड़ें गहराई तक जाती हैं और शाखाएँ आकाश तक फैलती हैं। वट वृक्ष दीर्घायु, अखण्डता और स्थिरता का प्रतीक है। जिस प्रकार वट वृक्ष सदा हरा-भरा रहता है, उसी प्रकार जो स्त्री इस व्रत को करती है, उसका सुहाग सदा अखण्ड रहता है।”

सावित्री ने पूछा —

“माँ! यह व्रत कब आरम्भ हुआ? क्या आपने इसे स्वयं स्थापित किया?”

माँ सावित्री ने कहा —

“पुत्रि! यह व्रत उस समय आरम्भ हुआ जब सृष्टि के आरम्भ में पतिव्रता धर्म की स्थापना हुई। सर्वप्रथम मैंने स्वयं अपने पति भगवान ब्रह्मा के लिए यह व्रत किया था। तब ब्रह्माजी ने प्रसन्न होकर मुझे वरदान दिया —

‘सावित्री! जो स्त्री तुम्हारी भाँति पतिव्रता का पालन करेगी और यह व्रत करेगी, उसका सुहाग अखण्ड रहेगा। उसके पति की आयु बढ़ेगी और उसे सन्तान-सुख प्राप्त होगा।’

तभी से यह व्रत चला आ रहा है। जब-जब धर्म की हानि होती है, तब-तब मैं पृथ्वी पर प्रकट होती हूँ। तुम मेरा ही स्वरूप हो — तुमने यमराज से लड़कर अपने पति को जीवनदान दिलाया। यही पतिव्रता धर्म का सर्वोच्च उदाहरण है।”

वट वृक्ष का महात्म्य:

सावित्री ने पूछा —

“माँ! वट वृक्ष का क्या महात्म्य है? इसे इतना पवित्र क्यों माना जाता है?”

माँ सावित्री ने कहा —

“पुत्रि! सुनो, वट वृक्ष को अक्षय वट कहा जाता है। यह वही वृक्ष है जिसकी छाया में भगवान विष्णु ने वामन अवतार में राजा बलि से तीन पग भूमि माँगी थी। यह वही वृक्ष है जिसके नीचे भगवान शिव ने तपस्या की थी। यह वही वृक्ष है जिसके नीचे माँ सरस्वती ने वेदों का ज्ञान दिया था।

वट वृक्ष के तीन गुण हैं —

1. अक्षयता: वट वृक्ष की आयु हज़ारों वर्ष होती है। यह कभी नष्ट नहीं होता। यह अखण्ड सुहाग का प्रतीक है।
2. स्थिरता: वट वृक्ष की जड़ें बहुत गहरी होती हैं। यह धर्म में स्थिरता का प्रतीक है।
3. विस्तार: वट वृक्ष की शाखाएँ आकाश तक फैलती हैं और इसकी जड़ों से नए पेड़ उगते हैं। यह वंश-वृद्धि का प्रतीक है।

जो स्त्री वट वृक्ष की पूजा करती है, उसे अखण्ड सौभाग्य, धर्म में स्थिरता और वंश-वृद्धि का आशीर्वाद मिलता है।”

सावित्री ने पूछा —

“माँ! वट वृक्ष की परिक्रमा क्यों की जाती है? सूत्र क्यों लपेटा जाता है?”

माँ सावित्री ने कहा —

“पुत्रि! वट वृक्ष की परिक्रमा का विशेष महात्म्य है। परिक्रमा का अर्थ है — अपने अहंकार को त्यागकर वृक्ष के चारों ओर घूमना। जब तुम वट वृक्ष की परिक्रमा करती हो, तब तुम वृक्ष को अपने पति का प्रतीक मानकर उसकी सेवा करती हो। सात परिक्रमा सात वचनों का प्रतीक है — जो स्त्री विवाह में सात फेरों में लेती है।

सूत्र लपेटने का अर्थ है — अपने सुहाग को वृक्ष से बाँधना। कच्चा सूत लपेटकर तुम वट वृक्ष से प्रार्थना करती हो कि जैसे यह सूत वृक्ष से बँधा है, वैसे ही तुम्हारा सुहाग भी अखण्ड रहे।”

व्रत की विधि:

सावित्री ने पूछा —

“माँ! कृपया मुझे इस व्रत की सम्पूर्ण विधि विस्तार से बताइए।”

माँ सावित्री ने कहा —

“पुत्रि! सुनो, विधि इस प्रकार है —

1. संकल्प: ज्येष्ठ मास की शुक्ल त्रयोदशी के दिन प्रातः ब्रह्ममुहूर्त में स्नान करो। स्वच्छ वस्त्र पहनकर वट वृक्ष के सम्मुख बैठो। हाथ में जल और अक्षत लेकर संकल्प करो —

‘ॐ सावित्र्यै नमः। मैं अपने पति की दीर्घायु और अखण्ड सौभाग्य के लिए यह व्रत करती हूँ।’

2. व्रत: दिनभर फलाहार या निराहार रहो। अस्वस्थता में शास्त्र और चिकित्सक के परामर्श का पालन करो।

3. वट वृक्ष का पूजन: सायंकाल वट वृक्ष के नीचे जाओ। वृक्ष की जड़ में जल अर्पित करो। रोली से वृक्ष पर तिलक करो। अक्षत, पुष्प, फल, मिष्ठान अर्पित करो। धूप और दीपक जलाओ।

4. सूत्र लपेटना: कच्चे सूत को वट वृक्ष के तने पर लपेटो। सात या ग्यारह परिक्रमा करो। प्रत्येक परिक्रमा में यह मंत्र बोलो —

‘ॐ सावित्र्यै नमः। वट सावित्री नमस्ते। मम सौभाग्यं देहि देहि।’

5. कथा श्रवण: वट सावित्री व्रत की कथा श्रद्धापूर्वक सुनो या पढ़ो।

6. आरती: माँ सावित्री और वट वृक्ष की आरती गाओ।

7. पारण: अगले दिन प्रातः स्नान करके पारण करो। पारण में अन्न ग्रहण करो।”

व्रत के नियम:

सावित्री ने पूछा —

“माँ! इस व्रत में किन नियमों का पालन करना चाहिए?”

माँ सावित्री ने कहा —

“पुत्रि! सुनो —

- व्रत के दिन सत्य बोलो, क्रोध मत करो, किसी की निन्दा मत करो।
- व्रत के दिन पति का अपमान मत करो। पति की सेवा करो।
- व्रत के दिन तामसिक भोजन — मांस, मदिरा, लहसुन, प्याज — ग्रहण मत करो।
- वट वृक्ष को कभी मत काटो। उसकी पत्तियाँ मत तोड़ो।
- वट वृक्ष की जड़ में जल अवश्य अर्पित करो।
- सूत्र लपेटते समय हाथ में कच्चा सूत लेकर वट वृक्ष को प्रणाम करो।
- व्रत के दिन दान अवश्य करो — अन्न, वस्त्र या धन।
- व्रत का संकल्प एक बार लेने के बाद उसे पूर्ण करो।
- यदि किसी कारण से कोई वर्ष छूट जाए, तो अगले वर्ष दोनों की पूर्ति करो।
- व्रत के दिन किसी भी जीव को हानि मत पहुँचाओ।
- पति के साथ वट वृक्ष की परिक्रमा अवश्य करो — यह अखण्ड सुहाग का प्रतीक है।
- वट वृक्ष के नीचे बैठकर माँ सावित्री का ध्यान करो।”

व्रत का फल:

सावित्री ने पूछा —

“माँ! इस व्रत से कौन-कौन से फल प्राप्त होते हैं?”

माँ सावित्री ने कहा —

“पुत्रि! जो स्त्री श्रद्धा और भक्ति से यह व्रत करती है —

- उसका सौभाग्य अखण्ड रहता है।
- उसके पति की आयु बढ़ती है।
- पति-पत्नी में प्रेम और विश्वास बढ़ता है।
- सन्तान-सुख की प्राप्ति होती है।
- सन्तानहीन को सन्तान-सुख मिलता है।
- घर में सुख, शान्ति और समृद्धि आती है।
- रोग और शोक दूर होते हैं।
- स्त्री का सुहाग अखण्ड रहता है।
- जो कन्या यह व्रत करती है, उसे मनोवांछित वर की प्राप्ति होती है।
- जो स्त्री पति-शोक से पीड़ित है, उसे शान्ति मिलती है।
- जो स्त्री सन्तान की इच्छा रखती है, उसे सन्तान-सुख मिलता है।
- जो स्त्री यह व्रत करती है, उसे अन्त में सावित्रीलोक की प्राप्ति होती है।

परन्तु पुत्रि, सबसे बड़ा फल यह है कि जो स्त्री यह व्रत करती है, उसके हृदय में पतिव्रता धर्म का वास हो जाता है। वह अपने पति को भगवान के समान देखती है और उसकी सेवा में अपना जीवन अर्पित कर देती है।”

सत्यवान-सावित्री की कथा का सार:

सावित्री ने पूछा —

“माँ! मेरी कथा से सभी स्त्रियों को क्या शिक्षा मिलती है?”

माँ सावित्री ने कहा —

“पुत्रि! तेरी कथा से यह शिक्षा मिलती है कि पतिव्रता और धर्म के बल से मृत्यु को भी पराजित किया जा सकता है। तूने यमराज से चार वर माँगे — पहले ससुर की दृष्टि, फिर ससुर को पुत्र-सुख, फिर पिता को पुत्र-सुख और अन्त में स्वयं सौ पुत्रों की माता बनने का वर। तूने अपने पति के प्राण सीधे नहीं माँगे, बल्कि धर्म के बंधन से यमराज को बाँधकर प्राण वापस लिए।

इससे यह शिक्षा मिलती है कि —

1. धर्म सर्वोपरि है: यदि तुम धर्म के मार्ग पर चलोगी, तो स्वयं देवता भी तुम्हारे सामने झुकेंगे।
2. पतिव्रता में अपार शक्ति है: जो स्त्री पतिव्रता का पालन करती है, वह असम्भव को भी सम्भव कर सकती है।
3. बुद्धि और धैर्य आवश्यक हैं: सावित्री ने रोकर यमराज से प्राण नहीं माँगे, बल्कि बुद्धि से उन्हें धर्म के बंधन में बाँधा।
4. वट वृक्ष की शरण में शक्ति है: वट वृक्ष अक्षयता का प्रतीक है। जो उसकी शरण में आता है, उसे अखण्ड सौभाग्य मिलता है।
5. स्त्री शक्ति अजेय है: सावित्री ने सिद्ध किया कि स्त्री केवल अबला नहीं, वह सबला है — वह मृत्यु को भी चुनौती दे सकती है।”

फलश्रुति:

माँ सावित्री ने कहा —

“पुत्रि! जो व्यक्ति इस वट सावित्री व्रत कथा को श्रद्धापूर्वक सुनता है, वह इस व्रत का सम्पूर्ण फल प्राप्त करता है। जो स्त्री इस कथा को सुनकर व्रत करती है, उसका सुहाग अखण्ड रहता है। जो कन्या इस कथा को सुनती है, उसे योग्य वर मिलता है। जो पुरुष इस कथा को सुनता है, उसकी पत्नी की आयु बढ़ती है।

जो इस कथा को पढ़ता या सुनाता है, उसे मेरी विशेष कृपा प्राप्त होती है। यह कथा जिस घर में सुनी जाती है, वहाँ सुख, समृद्धि और शान्ति बनी रहती है। जो इस कथा को प्रत्येक वट सावित्री व्रत में सुनता है, उसकी सभी मनोकामनाएँ पूर्ण होती हैं।

जो स्त्री यह व्रत करती है, उसे पतिव्रता धर्म का पालन अवश्य करना चाहिए। यदि वह पति का अपमान करती है, तो उसका व्रत निष्फल हो जाता है। इसलिए सभी स्त्रियों को चाहिए कि वे पति की सेवा करें, उनका आदर करें और उन्हें भगवान के समान मानें।”

समापन:

इसके बाद माँ सावित्री ने सावित्री को आशीर्वाद दिया —

“पुत्रि! तेरा सुहाग अखण्ड रहे। तेरे पति की आयु लम्बी हो। तेरे पुत्र सौ पुत्रों के समान यशस्वी हों। तूने जो यह व्रत किया और यमराज को पराजित किया, वह सदा तेरे कुल की रक्षा करेगा। अब तू घर जा और अपने परिवार के साथ सुख से रह। मैं सदा तुम्हारी रक्षा करूँगी।”

यह कहकर माँ सावित्री अन्तर्धान हो गईं।

सावित्री ने प्रातःकाल वट वृक्ष को प्रणाम किया और घर लौटी। उसने सत्यवान को सारी बात बताई — कैसे माँ सावित्री ने दर्शन दिए और व्रत का सम्पूर्ण महात्म्य बताया।

सत्यवान ने कहा —

“सावित्री! तुम धन्य हो। माँ सावित्री ने तुम्हें स्वयं दर्शन दिए। अब तुम सभी स्त्रियों को इस व्रत का महात्म्य बताओ।”

सावित्री ने उस दिन से वट सावित्री व्रत का प्रचार आरम्भ किया। उसने सभी स्त्रियों को वट वृक्ष की पूजा करना सिखाया और उन्हें पतिव्रता धर्म का महात्म्य बताया।

धीरे-धीरे यह व्रत सारे राज्य में प्रसिद्ध हो गया। प्रत्येक वर्ष ज्येष्ठ मास की शुक्ल त्रयोदशी को सभी सुहागिन स्त्रियाँ वट वृक्ष के नीचे एकत्र होकर माँ सावित्री की पूजा करने लगीं। वे सूत्र लपेटतीं, परिक्रमा करतीं और कथा सुनतीं।

सावित्री और सत्यवान के सौ पुत्र हुए — सभी धर्मात्मा और यशस्वी। द्युमत्सेन का राज्य फलता-फूलता रहा और राजा अश्वपति का राज्य भी सुरक्षित रहा।

एक दिन सत्यवान ने सावित्री से पूछा —

“प्रिये! तुमने माँ सावित्री से जो ज्ञान प्राप्त किया, वह सभी को कैसे पहुँचेगा?”

सावित्री ने कहा —

“स्वामी! मैं इस व्रत का प्रचार करूँगी और सभी स्त्रियों को पतिव्रता धर्म का महात्म्य बताऊँगी। जो स्त्री इस व्रत को श्रद्धा से करेगी, उसका सुहाग अखण्ड रहेगा।”

