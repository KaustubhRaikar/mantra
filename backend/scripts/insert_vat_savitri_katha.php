“स्वामी! आप मेरी गोद में सिर रखिए। मैं आपके पास हूँ।”

सत्यवान ने अपना सिर सावित्री की गोद में रख दिया। उसकी आँखें धीरे-धीरे बंद होने लगीं। उसके शरीर की गर्मी कम होने लगी। उसने अंतिम शब्द कहे —

“सावित्री! तुम मेरे जीवन का सबसे बड़ा वरदान हो। मेरे माता-पिता का ध्यान रखना।”

यह कहकर सत्यवान की आँखें स्थिर हो गईं। उसके प्राण शरीर से निकल गए। सावित्री की गोद में सत्यवान का शरीर शान्त पड़ा था — मुख पर वही शान्ति थी, परन्तु प्राण नहीं थे।

सावित्री रोई नहीं। उसका हृदय शोक से भरा था, परन्तु उसका संकल्प अटल था। उसने सत्यवान के सिर को अपनी गोद में सम्भाला और आकाश की ओर देखकर कहा —

“ॐ सावित्र्यै नमः। हे माँ! मैं जानती हूँ कि यमराज अभी आने वाले हैं। मैं अपने पति के प्राण वापस लाऊँगी। मैंने 364 दिन तक वट वृक्ष के नीचे आपकी उपासना की है। आप मेरी शक्ति बनें।”

उसी क्षण आकाश में एक विचित्र प्रकाश फैल गया। वन में अचानक सन्नाटा छा गया। पक्षियों ने चहचहाना बंद कर दिया। हवा रुक गई। सावित्री ने देखा — दक्षिण दिशा से एक दिव्य पुरुष आ रहे हैं। उनका शरीर काला था, वस्त्र लाल थे, हाथों में पाश और दण्ड थे। उनके मुख पर कोई भाव नहीं था — केवल गम्भीरता। उनके साथ दो भयानक रूप वाले दूत भी थे।

सावित्री जान गई — ये स्वयं यमराज हैं।

यमराज सत्यवान के शरीर के पास पहुँचे। उन्होंने अपना पाश उठाया और सत्यवान के शरीर से प्राण निकालने लगे। उस समय सत्यवान के प्राण एक छोटे तेजस्वी पुरुष के रूप में प्रकट हुए। यमराज ने उन्हें अपने पाश में बाँध लिया।

सावित्री ने हाथ जोड़कर यमराज से कहा —

“महाराज! आपका आगमन मुझे ज्ञात है। आप सत्यवान के प्राण लेने आए हैं। परन्तु मैं आपसे कुछ प्रार्थना करना चाहती हूँ।”

यमराज ने सावित्री की ओर देखा। उन्होंने ऐसी स्त्री को देखा जो रो नहीं रही थी, जिसका मुख शान्त था, जिसकी आँखों में केवल करुणा थी। वे आश्चर्यचकित हुए और बोले —

“सावित्री! तुम जानती हो कि मैं कौन हूँ?”

सावित्री ने कहा —

“महाराज! आप यमराज हैं — मृत्यु के देवता, कर्म के अधिपति। आप सभी प्राणियों के प्राण हरते हैं। आपका कोई अपराध नहीं। परन्तु मैं अपने पति के प्राण वापस लेना चाहती हूँ।”

यमराज ने कहा —

“सावित्री! तुम पतिव्रता हो, यह मैं जानता हूँ। परन्तु मृत्यु का विधान अटल है। सत्यवान की आयु पूरी हो चुकी है। मैं उसके प्राण लेकर जा रहा हूँ। तुम इसे रोक नहीं सकती।”

सावित्री ने कहा —

“महाराज! मैं आपके विधान का अनादर नहीं करती। परन्तु एक पतिव्रता स्त्री के लिए उसके पति का जीवन ही सर्वस्व है। मैं जानती हूँ कि आप धर्मराज हैं। आप सत्य और न्याय के देवता हैं। क्या आप मुझे कुछ वर देने की कृपा करेंगे?”

यमराज मुस्कुराए —

“सावित्री! तुमने अपने पति के लिए जो तपस्या की है, वह मैं जानता हूँ। तुम्हारी पतिव्रता से मैं प्रसन्न हूँ। तुम जो माँगना चाहो, माँगो — परन्तु सत्यवान के प्राण मैं नहीं दे सकता।”

सावित्री ने एक क्षण सोचा और बोली —

“महाराज! तब मुझे पहला वर दीजिए — मेरे अंधे ससुर द्युमत्सेन की दृष्टि लौट आए और उन्हें उनका खोया हुआ राज्य पुनः मिल जाए।”

यमराज ने कहा —

“सावित्री! तुम्हारा पहला वर स्वीकार किया जाता है। द्युमत्सेन की दृष्टि लौट आएगी और उन्हें उनका राज्य पुनः प्राप्त होगा। अब तुम अपना दूसरा वर माँगो।”

सावित्री ने कहा —

“महाराज! मेरा दूसरा वर यह है — मेरे ससुर और सास को पुत्र-सुख की प्राप्ति हो। वे सत्यवान को अपने पुत्र के रूप में खो चुके हैं, अब उन्हें सौ पुत्रों का सुख मिले।”

यमराज ने कहा —

“सावित्री! तुम्हारा दूसरा वर भी स्वीकार किया जाता है। द्युमत्सेन और उनकी पत्नी को सौ पुत्रों का सुख प्राप्त होगा। अब तुम तीसरा वर माँगो।”

सावित्री ने कहा —

“महाराज! मेरा तीसरा वर यह है — मेरे पिता राजा अश्वपति को पुत्र-सुख प्राप्त हो और उनका राज्य सदा सुरक्षित रहे।”

यमराज ने कहा —

“सावित्री! तुम्हारा तीसरा वर भी स्वीकार किया जाता है। राजा अश्वपति को पुत्र-सुख प्राप्त होगा और उनका राज्य सदा सुरक्षित रहेगा। अब तुम चौथा वर माँगो — परन्तु याद रखना, सत्यवान के प्राण नहीं।”

सावित्री ने एक गहरी साँस ली। उसने यमराज की ओर देखा और कहा —

“महाराज! मेरा चौथा वर यह है — मुझे सौ पुत्रों की माता बनने का सौभाग्य प्राप्त हो।”

यमराज ने बिना सोचे कहा —

“सावित्री! तुम्हारा चौथा वर भी स्वीकार किया जाता है। तुम सौ पुत्रों की माता बनोगी।”

सावित्री ने तुरन्त कहा —

“महाराज! आपने मुझे सौ पुत्रों की माता बनने का वर दिया है। परन्तु एक पतिव्रता स्त्री के लिए उसके पति के बिना पुत्रों की प्राप्ति कैसे सम्भव है? यह तो धर्म के विरुद्ध है। यदि मैं सत्यवान के बिना सौ पुत्रों की माता नहीं बन सकती, तो आपको मुझे सत्यवान के प्राण लौटाने होंगे।”

यमराज स्तब्ध रह गए। उन्होंने सावित्री की ओर देखा — वह शान्त खड़ी थी, उसके मुख पर कोई अहंकार नहीं था, केवल धर्म का प्रश्न था। यमराज ने सोचा — “यह स्त्री धर्म के ज्ञान में मुझसे भी आगे है।”

यमराज ने कहा —

“सावित्री! तुमने मुझे धर्म के बंधन में बाँध लिया है। मैंने तुम्हें सौ पुत्रों का वर दिया है और यह वर मेरे लिए भी अटल है। यदि तुम सौ पुत्रों की माता बनोगी, तो सत्यवान का जीवित होना अनिवार्य है। इसलिए मैं सत्यवान के प्राण लौटा रहा हूँ।”

यमराज ने अपना पाश खोला और सत्यवान के प्राण उसके शरीर में लौटा दिए। उन्होंने सावित्री से कहा —

“सावित्री! तुम धन्य हो। तुमने अपनी पतिव्रता, बुद्धि और धर्म के बल से मृत्यु को भी पराजित कर दिया। आज से तुम्हारी कथा तीनों लोकों में गाई जाएगी। जो स्त्री तुम्हारी कथा सुनेगी और वट सावित्री व्रत करेगी, उसका सुहाग अखण्ड रहेगा।”

यह कहकर यमराज अन्तर्धान हो गए।

सावित्री ने अपने पति के शरीर को देखा। सत्यवान की छाती धीरे-धीरे उठने लगी, आँखें खुलीं और उसने सावित्री को अपने सम्मुख देखा —

“प्रिये! क्या मैं सो गया था? मुझे ऐसा लगा जैसे मैंने कोई स्वप्न देखा हो। मैंने देखा कि एक काला पुरुष मुझे ले जा रहा था और तुम उससे बातें कर रही थीं।”

सावित्री ने मुस्कुराकर कहा —

“स्वामी! वह स्वप्न नहीं था। यमराज आपके प्राण लेने आए थे। मैंने अपने तप, पतिव्रता और धर्म के बल से आपके प्राण वापस लिए।”

सत्यवान ने आश्चर्य से कहा —

“सावित्री! तुमने मुझे मृत्यु से बचाया? यह कैसे सम्भव हुआ?”

सावित्री ने सारी बात सुनाई — कैसे उसने 364 दिन तक वट वृक्ष के नीचे माँ सावित्री की उपासना की, कैसे यमराज आए, कैसे उसने चार वर माँगे और कैसे चौथे वर से यमराज को धर्म के बंधन में बाँधा।

सत्यवान ने सुनकर सावित्री के चरण पकड़ लिए —

“सावित्री! तुम मेरी पत्नी नहीं, मेरी देवी हो। तुमने मुझे जीवनदान दिया। मैं तुम्हारा ऋणी हूँ।”

सावित्री ने सत्यवान को उठाया और कहा —

“स्वामी! यह सब माँ सावित्री की कृपा है। अब हमें घर चलना चाहिए। माता-पिता चिन्तित होंगे।”

दोनों घर लौटे। जब वे आश्रम पहुँचे, तो देखा — द्युमत्सेन अपनी आँखों से देख रहे थे! उनकी दृष्टि लौट आई थी। सावित्री ने उन्हें यमराज का वरदान सुनाया। द्युमत्सेन ने आकाश की ओर हाथ उठाकर कहा —

“ॐ सावित्र्यै नमः। हे माँ! आपने हमें हमारी दृष्टि लौटाई। हम सदा आपके ऋणी रहेंगे।”

उसी समय एक दूत आया और उसने सूचना दी — “द्युमत्सेन का राज्य उन्हें पुनः प्राप्त हो गया है। उनके भाई ने राज्य छोड़ दिया है और वे द्युमत्सेन को वापस बुला रहे हैं।”

द्युमत्सेन ने यह सुना तो वे आनन्द से भर गए। उन्होंने सावित्री को गले लगाया —

“पुत्रि! तूने हमें सब कुछ लौटा दिया — दृष्टि, राज्य और पुत्र। तू हमारी सच्ची पुत्री है।”

सावित्री और सत्यवान वन से विदा होकर राज्य की ओर चल पड़े। रास्ते में सावित्री ने वट वृक्ष को प्रणाम किया और कहा —

“हे वट वृक्ष! तुमने मुझे आश्रय दिया, तुमने मेरी उपासना सुनी। तुम सदा मेरे साथ रहोगे।”

वट वृक्ष की पत्तियाँ हवा में सरसराने लगीं — मानो वृक्ष ने सावित्री को आशीर्वाद दिया हो।

राजधानी पहुँचकर द्युमत्सेन को पुनः राज्य मिला। सारे राज्य में उत्सव मनाया गया। राजा अश्वपति को भी पुत्र-सुख का वरदान मिला। कुछ समय पश्चात राजा अश्वपति के पुत्र हुआ और द्युमत्सेन की पत्नी के भी सौ पुत्र हुए — उनमें सत्यवान सबसे बड़ा था।

सावित्री और सत्यवान सुखपूर्वक राज्य का शासन करने लगे। सावित्री ने प्रत्येक वर्ष ज्येष्ठ मास की शुक्ल त्रयोदशी को वट सावित्री व्रत करना आरम्भ किया। उसने सभी स्त्रियों को इस व्रत का महात्म्य बताया और उन्हें वट वृक्ष की पूजा करने की प्रेरणा दी।

एक दिन सत्यवान ने सावित्री से पूछा —

“प्रिये! तुमने यमराज से जो वर माँगे, उनमें सत्यवान के प्राण सीधे क्यों नहीं माँगे? तुमने चार वर माँगकर अन्त में मुझे जीवनदान दिलाया — यह कैसे सम्भव हुआ?”

सावित्री ने मुस्कुराकर कहा —

“स्वामी! यमराज धर्म के देवता हैं। यदि मैंने सीधे आपके प्राण माँगे होते, तो वे मना कर देते। परन्तु मैंने धर्म के बंधन में उन्हें बाँधा। जब मैंने चौथा वर — सौ पुत्रों की माता बनने का — माँगा, तो यमराज ने बिना सोचे वर दे दिया। परन्तु एक पतिव्रता स्त्री के लिए पति के बिना पुत्र कैसे सम्भव है? इस प्रकार यमराज स्वयं अपने वचन से बंध गए और उन्हें आपके प्राण लौटाने पड़े।”

सत्यवान ने सावित्री की बुद्धि देखी और आश्चर्यचकित रह गए —

“सावित्री! तुमने धर्म के बल से यमराज को भी पराजित किया। तुम साक्षात् माँ सावित्री का स्वरूप हो।”

