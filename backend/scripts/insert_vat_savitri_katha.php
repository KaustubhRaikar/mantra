“ॐ सावित्र्यै नमः। हे माँ! आपने मुझे यमराज से लड़ने की शक्ति दी। अब कृपया मुझे इस व्रत का सम्पूर्ण महात्म्य बताइए, जिससे मैं इसे सभी स्त्रियों तक पहुँचा सकूँ।”

