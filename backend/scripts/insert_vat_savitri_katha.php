वट वृक्ष को अक्षय वट कहा जाता है। यह वही वृक्ष है जिसके नीचे भगवान विष्णु ने वामन अवतार में राजा बलि से तीन पग भूमि माँगी थी। यह वही वृक्ष है जिसके नीचे भगवान शिव ने तपस्या की थी। यह वही वृक्ष है जिसके नीचे माँ सरस्वती ने वेदों का ज्ञान दिया था। यह वही वृक्ष है जिसके नीचे भगवान ब्रह्मा ने सृष्टि की रचना की थी।

वट वृक्ष के तीन गुण हैं —

1. अक्षयता: वट वृक्ष की आयु हज़ारों वर्ष होती है। यह कभी नष्ट नहीं होता। यह अखण्ड सुहाग का प्रतीक है।
2. स्थिरता: वट वृक्ष की जड़ें बहुत गहरी होती हैं। यह धर्म में स्थिरता का प्रतीक है।
3. विस्तार: वट वृक्ष की शाखाएँ आकाश तक फैलती हैं और इसकी जड़ों से नए पेड़ उगते हैं। यह वंश-वृद्धि का प्रतीक है।

जो स्त्री वट वृक्ष की पूजा करती है, उसे अखण्ड सौभाग्य, धर्म में स्थिरता और वंश-वृद्धि का आशीर्वाद मिलता है।”

वट सावित्री व्रत का प्रादुर्भाव:

सावित्री ने पूछा —

“महात्मन्! यह व्रत कब आरम्भ हुआ? क्या इसका उल्लेख वेदों में भी है?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! यह व्रत उस समय आरम्भ हुआ जब सृष्टि के आरम्भ में पतिव्रता धर्म की स्थापना हुई। सर्वप्रथम माँ सावित्री ने स्वयं अपने पति भगवान ब्रह्मा के लिए यह व्रत किया था। तब ब्रह्माजी ने प्रसन्न होकर उन्हें वरदान दिया —

‘सावित्री! जो स्त्री तुम्हारी भाँति पतिव्रता का पालन करेगी और यह व्रत करेगी, उसका सुहाग अखण्ड रहेगा। उसके पति की आयु बढ़ेगी और उसे सन्तान-सुख प्राप्त होगा।’

तभी से यह व्रत चला आ रहा है। ऋग्वेद में सावित्री देवी की स्तुति मिलती है —

‘ॐ सावित्र्यै नमः। सावित्रीं देवीं शरणं प्रपद्ये।’

गायत्री मंत्र में भी सावित्री का ही आह्वान है —

‘ॐ भूर्भुवः स्वः तत्सवितुर्वरेण्यं भर्गो देवस्य धीमहि धियो यो नः प्रचोदयात्॥’

