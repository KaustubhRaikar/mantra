रामायण काल में भी सावित्री की कथा का उल्लेख मिलता है। महाभारत के वन पर्व में सावित्री-सत्यवान की कथा विस्तार से वर्णित है। व्यासजी ने इस कथा को अमर बना दिया है।”

व्रत के चार दिनों का गूढ़ रहस्य:

सावित्री ने पूछा —

“महात्मन्! इस व्रत का क्या गूढ़ रहस्य है? इसमें किन-किन बातों का विशेष महत्व है?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! सुनो —

1. संकल्प: प्रातः स्नान करके संकल्प लेना — यह शुद्धि का प्रतीक है। संकल्प के बिना कोई व्रत सफल नहीं होता।
2. वट वृक्ष का पूजन: वट वृक्ष की जड़ में जल अर्पित करना — यह उस अक्षय शक्ति का आह्वान है जो सुहाग की रक्षा करती है। रोली से तिलक करना — यह सौभाग्य का प्रतीक है। अक्षत अर्पित करना — यह अखण्डता का प्रतीक है।
3. सूत्र लपेटना: कच्चे सूत को वट वृक्ष पर लपेटना — यह अपने सुहाग को वृक्ष से बाँधने का प्रतीक है। जैसे सूत वृक्ष से बँधा रहता है, वैसे ही सुहाग अखण्ड रहे।
4. परिक्रमा: वट वृक्ष की सात परिक्रमा करना — यह विवाह के सात फेरों का प्रतीक है। प्रत्येक परिक्रमा में पति का स्मरण करना — यह पतिव्रता धर्म का पालन है।
5. कथा श्रवण: सावित्री-सत्यवान की कथा सुनना — यह पतिव्रता धर्म का श्रवण है। जो कथा सुनता है, उसके हृदय में पतिव्रता का बीज बोया जाता है।
6. पारण: अगले दिन पारण करना — यह व्रत की पूर्णता का प्रतीक है।”

अर्घ्य और वट वृक्ष की परिक्रमा का महात्म्य:

सावित्री ने पूछा —

“महात्मन्! वट वृक्ष की परिक्रमा का क्या महात्म्य है? सूत्र क्यों लपेटा जाता है?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! वट वृक्ष की परिक्रमा का विशेष महात्म्य है। परिक्रमा का अर्थ है — अपने अहंकार को त्यागकर वृक्ष के चारों ओर घूमना। जब तुम वट वृक्ष की परिक्रमा करती हो, तब तुम वृक्ष को अपने पति का प्रतीक मानकर उसकी सेवा करती हो। सात परिक्रमा सात वचनों का प्रतीक है — जो स्त्री विवाह में सात फेरों में लेती है।

सूत्र लपेटने का अर्थ है — अपने सुहाग को वृक्ष से बाँधना। कच्चा सूत लपेटकर तुम वट वृक्ष से प्रार्थना करती हो कि जैसे यह सूत वृक्ष से बँधा है, वैसे ही तुम्हारा सुहाग भी अखण्ड रहे।

सूत्र लपेटते समय यह मंत्र बोलो —

‘ॐ सावित्र्यै नमः। वट सावित्री नमस्ते। मम सौभाग्यं देहि देहि।’

इस मंत्र का अर्थ है — हे वट सावित्री! आपको नमस्कार है। मुझे सौभाग्य प्रदान करें।”

व्रत के नियम:

सावित्री ने पूछा —

“महात्मन्! इस व्रत में किन नियमों का पालन करना चाहिए?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! सुनो —

- व्रत के दिन सत्य बोलो, क्रोध मत करो, किसी की निन्दा मत करो।
- व्रत के दिन पति का अपमान मत करो। पति की सेवा करो।
- व्रत के दिन तामसिक भोजन — मांस, मदिरा, लहसुन, प्याज — ग्रहण मत करो।
- वट वृक्ष को कभी मत काटो। उसकी पत्तियाँ मत तोड़ो।
- वट वृक्ष की जड़ में जल अवश्य अर्पित करो।
- सूत्र लपेटते समय हाथ में कच्चा सूत लेकर वट वृक्ष को प्रणाम करो।
- व्रत के दिन दान अवश्य करो — अन्न, वस्त्र या धन।
- व्रत का संकल्प एक बार लेने के बाद उसे पूर्ण करो।
- यदि किसी कारण से कोई वर्ष छूट जाए, तो अगले वर्ष दोनों की पूर्ति करो।
- व्रत के दिन किसी भी जीव को हानि मत पहुँचाओ।
- पति के साथ वट वृक्ष की परिक्रमा अवश्य करो — यह अखण्ड सुहाग का प्रतीक है।
- वट वृक्ष के नीचे बैठकर माँ सावित्री का ध्यान करो।
- व्रत के दिन पति के साथ वट वृक्ष के नीचे बैठकर सावित्री-सत्यवान की कथा सुनो।
- वट वृक्ष की जड़ में दूध और जल अर्पित करो — यह सुहाग की शीतलता का प्रतीक है।
- व्रत के दिन पति के चरण स्पर्श करके आशीर्वाद लो।”

व्रत का फल:

सावित्री ने पूछा —

“महात्मन्! इस व्रत से कौन-कौन से फल प्राप्त होते हैं?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! जो स्त्री श्रद्धा और भक्ति से यह व्रत करती है —

- उसका सौभाग्य अखण्ड रहता है।
- उसके पति की आयु बढ़ती है।
- पति-पत्नी में प्रेम और विश्वास बढ़ता है।
- सन्तान-सुख की प्राप्ति होती है।
- सन्तानहीन को सन्तान-सुख मिलता है।
- घर में सुख, शान्ति और समृद्धि आती है।
- रोग और शोक दूर होते हैं।
- स्त्री का सुहाग अखण्ड रहता है।
- जो कन्या यह व्रत करती है, उसे मनोवांछित वर की प्राप्ति होती है।
- जो स्त्री पति-शोक से पीड़ित है, उसे शान्ति मिलती है।
- जो स्त्री सन्तान की इच्छा रखती है, उसे सन्तान-सुख मिलता है।
- जो स्त्री यह व्रत करती है, उसे अन्त में सावित्रीलोक की प्राप्ति होती है।

परन्तु पुत्रि, सबसे बड़ा फल यह है कि जो स्त्री यह व्रत करती है, उसके हृदय में पतिव्रता धर्म का वास हो जाता है। वह अपने पति को भगवान के समान देखती है और उसकी सेवा में अपना जीवन अर्पित कर देती है।”

सावित्री-सत्यवान कथा का सार:

सावित्री ने पूछा —

“महात्मन्! मेरी कथा से सभी स्त्रियों को क्या शिक्षा मिलती है?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! तेरी कथा से यह शिक्षा मिलती है कि पतिव्रता और धर्म के बल से मृत्यु को भी पराजित किया जा सकता है।

तूने यमराज से चार वर माँगे — पहले ससुर की दृष्टि, फिर ससुर को पुत्र-सुख, फिर पिता को पुत्र-सुख और अन्त में स्वयं सौ पुत्रों की माता बनने का वर। तूने अपने पति के प्राण सीधे नहीं माँगे, बल्कि धर्म के बंधन से यमराज को बाँधकर प्राण वापस लिए।

इससे यह शिक्षा मिलती है कि —

1. धर्म सर्वोपरि है: यदि तुम धर्म के मार्ग पर चलोगी, तो स्वयं देवता भी तुम्हारे सामने झुकेंगे।
2. पतिव्रता में अपार शक्ति है: जो स्त्री पतिव्रता का पालन करती है, वह असम्भव को भी सम्भव कर सकती है।
3. बुद्धि और धैर्य आवश्यक हैं: सावित्री ने रोकर यमराज से प्राण नहीं माँगे, बल्कि बुद्धि से उन्हें धर्म के बंधन में बाँधा।
4. वट वृक्ष की शरण में शक्ति है: वट वृक्ष अक्षयता का प्रतीक है। जो उसकी शरण में आता है, उसे अखण्ड सौभाग्य मिलता है।
5. स्त्री शक्ति अजेय है: सावित्री ने सिद्ध किया कि स्त्री केवल अबला नहीं, वह सबला है — वह मृत्यु को भी चुनौती दे सकती है।”

सन्तानहीन स्त्रियों के लिए विशेष विधान:

सावित्री ने पूछा —

“महात्मन्! जो स्त्री सन्तानहीन है, वह क्या करे?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! जो स्त्री सन्तान की इच्छा रखती है, उसे यह व्रत विशेष रूप से करना चाहिए। उसे प्रत्येक वर्ष वट सावित्री व्रत करना चाहिए और माँ सावित्री से सन्तान की प्रार्थना करनी चाहिए। उसे वट वृक्ष की जड़ में दूध और जल अर्पित करना चाहिए। जो स्त्री श्रद्धा से यह व्रत करती है, उसे सन्तान-सुख अवश्य प्राप्त होता है।”

पति-शोक से पीड़ित स्त्रियों के लिए विशेष विधान:

सावित्री ने पूछा —

“महात्मन्! जो स्त्री पति-शोक से पीड़ित है, वह क्या करे?”

ऋषि वसिष्ठ ने कहा —

“पुत्रि! जो स्त्री पति-शोक से पीड़ित है, उसे यह व्रत विशेष रूप से करना चाहिए। उसे वट वृक्ष के नीचे बैठकर माँ सावित्री से प्रार्थना करनी चाहिए। माँ सावित्री ने स्वयं यमराज से अपने पति के प्राण वापस लिए थे — वे उस स्त्री के पति के प्राण भी लौटा सकती हैं। जो स्त्री श्रद्धा से यह व्रत करती है, उसे पति-शोक से मुक्ति मिलती है।”

फलश्रुति:

ऋषि वसिष्ठ ने कहा —

“पुत्रि! जो व्यक्ति इस वट सावित्री व्रत कथा को श्रद्धापूर्वक सुनता है, वह इस व्रत का सम्पूर्ण फल प्राप्त करता है। जो स्त्री इस कथा को सुनकर व्रत करती है, उसका सुहाग अखण्ड रहता है। जो कन्या इस कथा को सुनती है, उसे योग्य वर मिलता है। जो पुरुष इस कथा को सुनता है, उसकी पत्नी की आयु बढ़ती है।

जो इस कथा को पढ़ता या सुनाता है, उसे माँ सावित्री की विशेष कृपा प्राप्त होती है। यह कथा जिस घर में सुनी जाती है, वहाँ सुख, समृद्धि और शान्ति बनी रहती है। जो इस कथा को प्रत्येक वट सावित्री व्रत में सुनता है, उसकी सभी मनोकामनाएँ पूर्ण होती हैं।

जो स्त्री यह व्रत करती है, उसे पतिव्रता धर्म का पालन अवश्य करना चाहिए। यदि वह पति का अपमान करती है, तो उसका व्रत निष्फल हो जाता है। इसलिए सभी स्त्रियों को चाहिए कि वे पति की सेवा करें, उनका आदर करें और उन्हें भगवान के समान मानें।”

समापन:

ऋषि वसिष्ठ ने सावित्री को आशीर्वाद दिया —

“पुत्रि! तेरा सुहाग अखण्ड रहे। तेरे पति की आयु लम्बी हो। तेरे पुत्र सौ पुत्रों के समान यशस्वी हों। तूने जो यह व्रत किया और यमराज को पराजित किया, वह सदा तेरे कुल की रक्षा करेगा। अब तू घर जा और अपने परिवार के साथ सुख से रह। माँ सावित्री सदा तुम्हारी रक्षा करेंगी।”

सावित्री ने ऋषि को प्रणाम किया और कहा —

“महात्मन्! आपने मुझे वट सावित्री व्रत का सम्पूर्ण महात्म्य बताया। मैं आपकी ऋणी हूँ। अब मैं इस व्रत को और अधिक प्रचारित करूँगी।”

उस दिन से सावित्री ने वट सावित्री व्रत को अपने राज्य का राजधर्म घोषित कर दिया। प्रत्येक वर्ष ज्येष्ठ मास की शुक्ल त्रयोदशी को सारे राज्य में वट सावित्री व्रत का महोत्सव मनाया जाने लगा। सभी सुहागिन स्त्रियाँ वट वृक्ष के नीचे एकत्र होकर माँ सावित्री की पूजा करने लगीं।

सावित्री और सत्यवान ने अपने पुत्रों को भी यह व्रत सिखाया। उनके पुत्रों ने भी वट वृक्षों की रक्षा का संकल्प लिया और माँ सावित्री की भक्ति में लग गए।

धीरे-धीरे वट सावित्री व्रत सारे देश में प्रसिद्ध हो गया। लोग वट वृक्षों को पवित्र मानकर उनकी रक्षा करने लगे। जहाँ-जहाँ वट वृक्ष थे, वहाँ स्त्रियाँ एकत्र होकर पूजा करने लगीं।

आज भी भारत के अनेक भागों में — विशेष रूप से महाराष्ट्र, गुजरात, उत्तर प्रदेश, बिहार और मध्य प्रदेश में — वट सावित्री व्रत अत्यन्त श्रद्धा और उल्लास से मनाया जाता है। सुहागिन स्त्रियाँ वट वृक्ष के नीचे एकत्र होकर सूत्र लपेटती हैं, परिक्रमा करती हैं और सावित्री-सत्यवान की कथा सुनती हैं।

इति श्री वट सावित्री व्रत कथा सम्पूर्णम्।

ॐ सावित्र्यै नमः।
या देवी सर्वभूतेषु सावित्रीरूपेण संस्थिता।
नमस्तस्यै नमस्तस्यै नमस्तस्यै नमो नमः॥
